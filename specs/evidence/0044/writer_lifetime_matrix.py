def _ast_callers(keys) -> dict:
    """Every function in src/veracium that CALLS each ruling key by name (`x.key(...)` or `key(...)`), qualified."""
    out = {k: set() for k in keys}
    src = ROOT / "src" / "veracium"
    for path in sorted(src.rglob("*.py")):
        tree = ast.parse(path.read_text())
        rel = path.relative_to(src).as_posix()

        def visit(node, qual):
            for child in ast.iter_child_nodes(node):
                if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    visit(child, f"{qual}.{child.name}" if qual else child.name)
                    continue
                if isinstance(child, ast.Call):
                    f = child.func
                    name = f.attr if isinstance(f, ast.Attribute) else (f.id if isinstance(f, ast.Name) else None)
                    if name in out and qual:
                        out[name].add(f"{rel}:{qual}")
                visit(child, qual)
        visit(tree, "")
    return {k: sorted(v) for k, v in out.items()}


class GeneratorRefused(Exception):
    pass


def _pkg_rel(filename: str):
    """A frame's module path relative to the IMPORTED veracium package (`store/sqlite.py`), or None outside it. Never
    by splitting at "/veracium/": a checkout directory named `veracium` holds that segment above the package too (the
    repository's own does), which named every module `src/veracium/...` and counted test and spec frames as callers."""
    import veracium
    root = pathlib.Path(veracium.__file__).resolve().parent
    try:
        return pathlib.Path(filename).resolve().relative_to(root).as_posix()
    except ValueError:
        return None


def _record_run(fn, p, keys) -> tuple:
    """Drive `fn` on store `p` with the hook wrapped; returns (ending, hook calls). Only the store at `p` is recorded
    (an input's helper SOURCE store — an export to import — writes through the same class). A hook call with no ruling
    key on its chain raises GeneratorRefused (M4(c))."""
    from veracium.store.sqlite import SqliteStore
    calls = []
    real = SqliteStore._apply_lifetime_transition

    def recording(self, user_id, edge_id, prior_json, new_json):
        t = real(self, user_id, edge_id, prior_json, new_json)
        if self._path != p:
            return t
        frame, chain, caller = sys._getframe(1), [], None
        while frame is not None:
            code = frame.f_code
            if code.co_name in keys and code.co_filename.endswith("store/sqlite.py"):
                chain.append(code.co_name)
            frame = frame.f_back
        if not chain:
            raise GeneratorRefused(f"a lifetime hook call on edge {edge_id!r} passed through no ruling key")
        frame = sys._getframe(1)
        while frame is not None and frame.f_code.co_name != chain[-1]:
            frame = frame.f_back
        outer = frame.f_back if frame is not None else None
        mod = _pkg_rel(outer.f_code.co_filename) if outer is not None else None
        if mod is not None:
            qual = getattr(outer.f_code, "co_qualname", outer.f_code.co_name)
            caller = f"{mod}:{qual}"
        calls.append({"chain": list(reversed(chain)), "transition": "insert" if prior_json is None else (t or "none"),
                      "caller": caller})
        return t

    SqliteStore._apply_lifetime_transition = recording
    try:
        try:
            fn(p)
        except GeneratorRefused:
            raise
        except Exception as exc:                                    # noqa: BLE001 — a refusal is an ending
            import traceback
            last = [f for f in traceback.extract_tb(exc.__traceback__) if _pkg_rel(f.filename) is not None]
            where = (_pkg_rel(last[-1].filename) + ":" + last[-1].name) if last else "?"
            return f"refused: {type(exc).__name__} at {where}", calls
    finally:
        SqliteStore._apply_lifetime_transition = real
    return ("accepted" if calls else "no-hook-call"), calls


def _erasure_rows(p) -> int:
    c = sqlite3.connect(p)
    try:
        return sum(c.execute(f"SELECT COUNT(*) FROM {t} WHERE user_id=?", (U,)).fetchone()[0]
                   for t in ("arity_inventory", "migration_outcome", "migration_run"))
    finally:
        c.close()


def generate() -> dict:
    keys = _ruling_keys()
    runs = []
    with tempfile.TemporaryDirectory() as d:
        base_dir = pathlib.Path(d) / "base"
        base_dir.mkdir()
        from veracium.store.sqlite import SqliteStore
        real = SqliteStore._apply_lifetime_transition
        base = base_dir / "s.db"
        # the base's own build drives the data migration's restoration: recorded the same way, on the base store
        ending, base_calls = _record_run(lambda _: _store(base_dir), str(base), keys)
        for i, (name, meant, fn) in enumerate(INPUTS):
            if fn is None:
                runs.append({"input": name, "meant": meant, "ending": ending,
                             "calls": [c for c in base_calls if c["chain"][-1] == meant]})
                continue
            d_i = pathlib.Path(d) / f"in{i}"
            d_i.mkdir()
            import shutil
            shutil.copy(base, d_i / "s.db")
            p = str(d_i / "s.db")
            before = _erasure_rows(p)
            end, calls = _record_run(fn, p, keys)
            if meant == "forget_user" and end == "no-hook-call" and before and _erasure_rows(p) == 0:
                calls = [{"chain": ["forget_user"], "transition": "erasure", "caller": "(the store's public verb)"}]
                end = "accepted"
            runs.append({"input": name, "meant": meant, "ending": end, "calls": calls})
        assert SqliteStore._apply_lifetime_transition is real
    cells = {}
    for k in keys:
        for t in TRANSITIONS:
            obs = sorted({r["input"] for r in runs for c in r["calls"] if c["chain"][-1] == k and c["transition"] == t})
            if obs:
                cells[f"{k}|{t}"] = {"state": "observed", "inputs": obs}
            else:
                cells[f"{k}|{t}"] = {"state": "not-observed", "reason": REASONS.get((k, t)),
                                     "driven": [{"input": r["input"], "ending": r["ending"]} for r in runs
                                                if r["meant"] == k]}
    ast_callers = _ast_callers(keys)
    run_callers = {k: sorted({c["caller"] for r in runs for c in r["calls"]
                              if c["chain"][0] == k and c["caller"] and not c["caller"].startswith("(")}) for k in keys}
    return {"ruling_keys": {k: v.get("lifetime") for k, v in keys.items()}, "transitions": list(TRANSITIONS),
            "runs": runs, "cells": cells, "callers": {"ast": ast_callers, "run": run_callers}}


def problems(m: dict) -> list:
    """The generator's refusals over a matrix: a cell neither observed nor given a reason; a reason for an observed
    cell; a ruling key with no lifetime disposition; a run caller the AST list lacks; a chain with no ruling key."""
    out = []
    for k, life in m["ruling_keys"].items():
        if life not in ("choke-point", "erasure"):
            out.append(f"ruling key {k!r} carries no lifetime disposition ({life!r})")
    for cell, v in m["cells"].items():
        k, t = cell.split("|")
        if v["state"] == "not-observed" and not v.get("reason"):
            out.append(f"cell {cell} is neither observed nor given a reason")
        if v["state"] == "observed" and REASONS.get((k, t)):
            out.append(f"cell {cell} is observed, but REASONS says it is not reachable: {REASONS[(k, t)]!r}")
    for k in m["ruling_keys"]:
        for t in m["transitions"]:
            if f"{k}|{t}" not in m["cells"]:
                out.append(f"ruling key {k!r} has no cell for {t!r}")
    for k, callers in m["callers"]["run"].items():
        for c in callers:
            if c not in m["callers"]["ast"].get(k, []):
                out.append(f"run caller {c!r} of {k!r} is not in the AST caller list")
    return out


def render(m: dict) -> str:
    lines = ["# 0044 §4f-ii — the writer/lifetime matrix (GENERATED: `specs/evidence/0044/writer_lifetime_matrix.py`)",
             "", "Each cell: `observed` (the inputs that produced it, by running them) or not observed, with its reason.",
             "", "| ruling key (lifetime) | " + " | ".join(m["transitions"]) + " |",
             "|---|" + "---|" * len(m["transitions"])]
    for k, life in m["ruling_keys"].items():
        row = [f"`{k}` ({life})"]
        for t in m["transitions"]:
            v = m["cells"][f"{k}|{t}"]
            row.append(f"**observed** ({len(v['inputs'])})" if v["state"] == "observed" else "—")
        lines.append("| " + " | ".join(row) + " |")
    lines += ["", "## The driven inputs and how each ended", "", "| input | meant for | ending | hook calls (chain → transition) |",
              "|---|---|---|---|"]
    for r in m["runs"]:
        calls = "; ".join(f"{' → '.join(c['chain'])} → {c['transition']}" for c in r["calls"]) or "—"
        lines.append(f"| {r['input']} | `{r['meant']}` | {r['ending']} | {calls} |")
    lines += ["", "## Callers", "", "| ruling key | callers (AST over src/veracium) | callers seen in the run |", "|---|---|---|"]
    for k in m["ruling_keys"]:
        lines.append(f"| `{k}` | {', '.join(m['callers']['ast'][k]) or '—'} | {', '.join(m['callers']['run'][k]) or '—'} |")
    lines += ["", "## Not-observed cells, with their reasons", ""]
    for cell, v in m["cells"].items():
        if v["state"] == "not-observed":
            lines.append(f"- `{cell}`: {v['reason']}")
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    sys.path.insert(0, str(ROOT / "src"))
    m = generate()
    bad = problems(m)
    for b in bad:
        print("REFUSED:", b)
    if bad:
        return 1
    text, md = json.dumps(m, indent=1, sort_keys=True) + "\n", render(m)
    if "--write" in argv:
        OUT_JSON.write_text(text)
        OUT_MD.write_text(md)
        print(f"wrote {OUT_JSON.name} and {OUT_MD.name}: {len(m['ruling_keys'])} ruling keys × {len(m['transitions'])} "
              f"transitions, {sum(v['state'] == 'observed' for v in m['cells'].values())} cells observed, "
              f"{len(m['runs'])} inputs")
        return 0
    if "--check" in argv:
        stale = [n for n, want, got in ((OUT_JSON.name, text, OUT_JSON.read_text() if OUT_JSON.exists() else None),
                                        (OUT_MD.name, md, OUT_MD.read_text() if OUT_MD.exists() else None)) if want != got]
        if stale:
            print("STALE:", stale, "— regenerate with --write")
            return 1
        print("writer/lifetime matrix current")
        return 0
    sys.stdout.write(md)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
