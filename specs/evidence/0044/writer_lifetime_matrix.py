def _edge(eid, obj, *, rel="measures", user=U, at=None, reason=None, day=1, source=None, supersedes=None):
    from veracium.schema import Disclosure, Edge, EvidenceAuthor, Provenance
    return Edge(id=eid, user_id=user, subject="user", relation=rel, object=obj,
                valid_from=datetime(2026, 1, day, tzinfo=timezone.utc), invalidated_at=at, invalidation_reason=reason,
                supersedes=supersedes,
                provenance=Provenance(author_of_evidence=EvidenceAuthor.USER, evidence_ref=f"wlm-{eid}",
                                      disclosure=Disclosure.MENTIONABLE, source_id=source,
                                      observed_at=datetime(2026, 1, day, tzinfo=timezone.utc)))


def _store(d: pathlib.Path):
    """The base: a v14 store (the released schema) holding U's retired `p` (sourced `feed-1`) and its successor `n`, an
    active `f`, a retired `r` outside the reclassified names, and V's pair; migrated by the real v16 step, the data
    migration run (so `p` is restored with an outcome row)."""
    from veracium.schema import DEFAULT_RELATIONS
    from veracium.store import data_migration as DM
    from veracium.store import schema_version as sv
    from veracium.store.migration import migrate_store
    from veracium.store.release_migration import MigrationAttestation
    p = str(d / "s.db")
    edges = [_edge("p", "weight 78", at=T0, reason="superseded", source="feed-1"),
             _edge("n", "weight 80", day=2, supersedes="p", source="feed-1"),
             _edge("f", "Paris", rel="lives_in"),
             _edge("r", "Lisbon", rel="lives_in", at=T0, reason="disputed"),
             _edge("vp", "weight 60", user=V, at=T0, reason="superseded"), _edge("vn", "weight 61", user=V, day=2)]
    c = sqlite3.connect(p)
    sv.create(c, 14)
    for e in edges:
        c.execute("INSERT INTO edges(id,user_id,subject,relation,object,active,quarantined,json) VALUES(?,?,?,?,?,?,0,?)",
                  (e.id, e.user_id, e.subject, e.relation, e.object, int(e.invalidated_at is None), e.model_dump_json()))
    c.execute("PRAGMA user_version = 14")
    c.commit()
    c.close()
    migrate_store(p)
    r = DM.run_data_migration(p, host_attestation=MigrationAttestation(quiesced=True, backup_ref="wlm"),
                              registry=dict(DEFAULT_RELATIONS), op_id="op-wlm")
    assert r.outcome == "migrated", r
    return p


def _upsert(field_update, eid="r"):
    def run(p):
        from veracium.store.sqlite import SqliteStore
        from veracium.schema import Edge
        s = SqliteStore(p)
        try:
            e = Edge.model_validate_json(s._conn.execute("SELECT json FROM edges WHERE id=?", (eid,)).fetchone()[0])
            s.add_edge(e.model_copy(update=field_update(e)))
        finally:
            s.close()
    return run


